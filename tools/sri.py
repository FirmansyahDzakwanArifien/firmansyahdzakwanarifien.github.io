#!/usr/bin/env python3
"""Generate or verify Subresource Integrity hashes for the jsDelivr libraries in _data/origin/cors.yml.

  python3 tools/sri.py          # (re)write _data/sri.yml
  python3 tools/sri.py --check  # fail if any hash no longer matches what jsDelivr serves

Only version-pinned files are hashed, so the content (and the hash) never changes underneath us.
Templates add the hash through _includes/sri.html.
"""
import base64
import hashlib
import re
import sys
import urllib.request

CORS = "_data/origin/cors.yml"
OUT = "_data/sri.yml"
LOCALES = ["en"]  # dayjs locale files actually used (site.lang)
PINNED = re.compile(r"https://cdn\.jsdelivr\.net/npm/[^\s'\"]+@\d[^\s'\"/]*/[^\s'\"]+\.(?:js|css)")


def urls():
    text = open(CORS, encoding="utf-8").read()
    found = []
    for url in re.findall(r"https://cdn\.jsdelivr\.net/\S+", text):
        for expanded in ([url.replace(":LOCALE", loc) for loc in LOCALES] if ":LOCALE" in url else [url]):
            if PINNED.fullmatch(expanded) and expanded not in found:
                found.append(expanded)
    return found


def sri(url):
    req = urllib.request.Request(url, headers={"User-Agent": "cyphera-sri/1.0"})
    with urllib.request.urlopen(req, timeout=30) as res:
        return "sha384-" + base64.b64encode(hashlib.sha384(res.read()).digest()).decode()


def main():
    hashes = {url: sri(url) for url in urls()}

    if "--check" in sys.argv:
        current = dict(re.findall(r'^"([^"]+)":\s*(\S+)$', open(OUT, encoding="utf-8").read(), re.M))
        bad = [u for u in hashes if current.get(u) != hashes[u]]
        for u in bad:
            print(f"::error::SRI hash missing or stale for {u} (run python3 tools/sri.py)")
        print(f"Checked {len(hashes)} SRI hashes: {'all match' if not bad else f'{len(bad)} mismatched'}")
        sys.exit(1 if bad else 0)

    lines = ["# Generated by tools/sri.py from _data/origin/cors.yml. Do not edit by hand.", ""]
    lines += [f'"{u}": {h}' for u, h in hashes.items()]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"Wrote {len(hashes)} hashes to {OUT}")


if __name__ == "__main__":
    main()
