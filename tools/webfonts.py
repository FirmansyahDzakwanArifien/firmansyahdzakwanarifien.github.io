#!/usr/bin/env python3
"""Self-hosted web fonts: downloads the Google Fonts the site uses into assets/fonts/web/.

  python3 tools/webfonts.py

Writes assets/css/webfonts.css (theme: Source Sans Pro, Lato), assets/css/webfonts-home.css
(home page: Instrument Serif, DM Sans), and _data/webfonts.yml (the files head.html preloads).
Only the latin and latin-ext subsets are kept. font-display is swap, so the text always ends up in the
real font; serving the files from the same origin with a preload keeps the swap to the first visit.
"""
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets/fonts/web"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
SUBSETS = {"latin", "latin-ext"}
SHEETS = {
    "webfonts": "family=Lato:wght@300;400&family=Source+Sans+Pro:wght@400;600;700;900",
    "webfonts-home": "family=Instrument+Serif:ital@0;1&family=DM+Sans:opsz,wght@9..40,400..600",
}
# (sheet, family, style, weight) of the latin faces needed for the first paint: body text (400),
# sidebar links (600), sidebar title (900), headings (Lato 400), and the home page hero.
PRELOAD = [
    ("webfonts", "Source Sans Pro", "normal", "400"),
    ("webfonts", "Source Sans Pro", "normal", "600"),
    ("webfonts", "Source Sans Pro", "normal", "900"),
    ("webfonts", "Lato", "normal", "400"),
    ("webfonts-home", "DM Sans", "normal", "400 600"),
    ("webfonts-home", "Instrument Serif", "normal", "400"),
]


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60).read()


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def main():
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    for old in FONT_DIR.glob("*.woff2"):
        old.unlink()
    preload = {}
    for sheet, query in SHEETS.items():
        css = get(f"https://fonts.googleapis.com/css2?{query}&display=swap").decode("utf-8")
        out, files = [], {}
        for subset, face in re.findall(r"/\* ([a-z-]+) \*/\s*(@font-face\s*\{[^}]*\})", css):
            if subset not in SUBSETS:
                continue
            family = re.search(r"font-family:\s*'([^']+)'", face).group(1)
            style = re.search(r"font-style:\s*(\w+)", face).group(1)
            weight = re.search(r"font-weight:\s*([\d ]+);", face).group(1).strip()
            url = re.search(r"src:\s*url\(([^)]+)\)", face).group(1)
            if url not in files:  # variable fonts: several weights share one file
                name = f"{slug(family)}-{style}-{slug(weight)}-{subset}.woff2"
                (FONT_DIR / name).write_bytes(get(url))
                files[url] = name
            face = face.replace(url, f"../fonts/web/{files[url]}")
            out.append(f"/* {subset} */\n{face}")
            if subset == "latin":
                preload[(sheet, family, style, weight)] = f"/assets/fonts/web/{files[url]}"
        path = ROOT / f"assets/css/{sheet}.css"
        path.write_text("/* Self-hosted Google Fonts (tools/webfonts.py), SIL Open Font License. */\n"
                        + "\n".join(out) + "\n", encoding="utf-8", newline="\n")
        print(f"{path.relative_to(ROOT)}: {len(out)} faces, {len(files)} files")
    lines = ["# Generated by tools/webfonts.py: the font files head.html preloads, per stylesheet."]
    for sheet in SHEETS:
        lines.append(f"{sheet.replace('-', '_')}:")
        lines += [f"  - {preload[key]}" for key in PRELOAD if key[0] == sheet and key in preload]
    (ROOT / "_data/webfonts.yml").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    size = sum(f.stat().st_size for f in FONT_DIR.glob("*.woff2"))
    print(f"assets/fonts/web: {size // 1024} KB")


if __name__ == "__main__":
    main()
